/**
 * 단순 시·군·구 이름이 광역 정보 없이 텍스트에 등장 시 — 동명이면 null,
 * 유일하면 그 광역 + 자치단체 추론.
 */
export function detectStandaloneMuniWithSido(
  text: string,
): { sido: Sido; muni: string } | null {
  // 모든 광역 안의 모든 기초 자치단체 검색 (긴 이름 우선)
  type Entry = { sido: Sido; muni: string };
  const all: Entry[] = [];
  for (const [sido, list] of Object.entries(MUNICIPALITIES) as [Sido, readonly string[]][]) {
    for (const m of list) all.push({ sido, muni: m });
  }
  all.sort((a, b) => b.muni.length - a.muni.length);

  for (const e of all) {
    if (text.includes(e.muni)) {
      // 동명이면 null
      if (AMBIGUOUS_MUNICIPALITIES[e.muni]?.length) return null;
      return e;
    }
  }
  return null;
}
